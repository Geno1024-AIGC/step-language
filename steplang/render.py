@lru_cache(maxsize=4)
def _asset(name: str) -> str:
    return (_ASSETS / name).read_text(encoding="utf-8")


def _parse_hex(value: str) -> tuple[int, int, int]:
    raw = value.lstrip("#")
    if len(raw) in (3, 4):
        raw = "".join(ch * 2 for ch in raw[:3])
    elif len(raw) == 8:
        raw = raw[:6]
    try:
        return int(raw[0:2], 16), int(raw[2:4], 16), int(raw[4:6], 16)
    except (ValueError, IndexError):
        return 37, 99, 235


def _rgba(rgb: tuple[int, int, int], alpha: float) -> str:
    return f"rgba({rgb[0]}, {rgb[1]}, {rgb[2]}, {alpha:g})"


def _mix(rgb: tuple[int, int, int], other: tuple[int, int, int], ratio: float) -> str:
    return "#{:02x}{:02x}{:02x}".format(
        *(round(a + (b - a) * ratio) for a, b in zip(rgb, other))
    )


def _luminance(rgb: tuple[int, int, int]) -> float:
    def channel(value: int) -> float:
        value /= 255
        return value / 12.92 if value <= 0.04045 else ((value + 0.055) / 1.055) ** 2.4

    return 0.2126 * channel(rgb[0]) + 0.7152 * channel(rgb[1]) + 0.0722 * channel(rgb[2])


def _accent_css(accent: str) -> str:
    rgb = _parse_hex(accent)
    contrast = "#0b1220" if _luminance(rgb) > 0.45 else "#ffffff"
    ink_dark = _mix(rgb, (255, 255, 255), 0.42)
    return (
        ":root{"
        f"--accent:{accent};"
        f"--accent-soft:{_rgba(rgb, 0.11)};"
        f"--accent-soft-2:{_rgba(rgb, 0.18)};"
        f"--accent-border:{_rgba(rgb, 0.48)};"
        f"--accent-contrast:{contrast};"
        "}"
        "@media (prefers-color-scheme:dark){"
        f":root:not([data-theme=light]){{--link:{ink_dark}}}"
        "}"
        f":root[data-theme=dark]{{--link:{ink_dark}}}"
    )


def _json_for_html(value: object) -> str:
    raw = json.dumps(value, ensure_ascii=False, separators=(",", ":"))
    return (
        raw.replace("&", "\\u0026")
        .replace("<", "\\u003c")
        .replace(">", "\\u003e")
        .replace("\u2028", "\\u2028")
        .replace("\u2029", "\\u2029")
    )


def UI_for(lang: str) -> dict[str, str]:
    return UI["zh"] if lang.lower().startswith("zh") else UI["en"]


def _favicon(accent: str) -> str:
    rgb = _parse_hex(accent)
    contrast = "#0b1220" if _luminance(rgb) > 0.45 else "#ffffff"
    svg = (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32">'
        f'<rect width="32" height="32" rx="8" fill="{accent}"/>'
        f'<path d="M9 16.5l4.5 4.5L23 10.5" fill="none" stroke="{contrast}" '
        'stroke-width="3" stroke-linecap="round" stroke-linejoin="round"/>'
        "</svg>"
    )
    return "data:image/svg+xml," + quote(svg, safe="")


